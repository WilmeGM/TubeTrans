using YoutubeExplode.Videos.ClosedCaptions;

namespace Application.Helpers
{
    /// <summary>
    /// Chooses which caption track to use when a video offers several.
    /// </summary>
    public static class CaptionTrackSelector
    {
        /// <summary>
        /// Picks the caption track that most likely matches the video's original language.
        /// </summary>
        /// <param name="tracks">The available tracks, in the order returned by YouTube.</param>
        /// <returns>The selected track, or <c>null</c> if there are none.</returns>
        /// <remarks>
        /// YouTube does not expose the original audio language without its official API, so this is a
        /// heuristic. The rules are applied in order:
        /// <list type="number">
        ///   <item><description>No tracks: returns <c>null</c>.</description></item>
        ///   <item><description>A single track: returns it.</description></item>
        ///   <item><description>Exactly one manually created track (<see cref="ClosedCaptionTrackInfo.IsAutoGenerated"/> is <c>false</c>): returns it, since a creator-supplied track is usually in the main language.</description></item>
        ///   <item><description>Otherwise: returns the first track, assuming YouTube lists the main audio track first. This last rule is an assumption, not a guarantee.</description></item>
        /// </list>
        /// </remarks>
        public static ClosedCaptionTrackInfo? SelectPrimary(IReadOnlyList<ClosedCaptionTrackInfo> tracks)
        {
            if (tracks.Count == 0)
                return null;

            if (tracks.Count == 1)
                return tracks[0];

            var manualTracks = tracks.Where(t => !t.IsAutoGenerated).ToList();
            if (manualTracks.Count == 1)
                return manualTracks[0];

            return tracks[0];
        }
    }
}
