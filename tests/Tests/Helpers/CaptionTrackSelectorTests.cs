using Application.Helpers;
using YoutubeExplode.Videos.ClosedCaptions;

namespace Tests.Helpers
{
    public class CaptionTrackSelectorTests
    {
        private static ClosedCaptionTrackInfo Track(string code, string name, bool autoGenerated) =>
            new($"https://example.com/{code}", new Language(code, name), autoGenerated);

        [Fact]
        public void SelectPrimary_NoTracks_ReturnsNull()
        {
            Assert.Null(CaptionTrackSelector.SelectPrimary(Array.Empty<ClosedCaptionTrackInfo>()));
        }

        [Fact]
        public void SelectPrimary_SingleTrack_ReturnsIt()
        {
            var only = Track("es", "Spanish", autoGenerated: true);

            Assert.Same(only, CaptionTrackSelector.SelectPrimary(new[] { only }));
        }

        [Fact]
        public void SelectPrimary_OneManualAmongAutoGenerated_ReturnsTheManualOne()
        {
            var auto = Track("en", "English", autoGenerated: true);
            var manual = Track("es", "Spanish", autoGenerated: false);

            Assert.Same(manual, CaptionTrackSelector.SelectPrimary(new[] { auto, manual }));
        }

        [Fact]
        public void SelectPrimary_AllAutoGenerated_ReturnsFirstOne()
        {
            var first = Track("en", "English", autoGenerated: true);
            var second = Track("es", "Spanish", autoGenerated: true);

            Assert.Same(first, CaptionTrackSelector.SelectPrimary(new[] { first, second }));
        }

        [Fact]
        public void SelectPrimary_SeveralManualTracks_FallsBackToFirstOverall()
        {
            var first = Track("en", "English", autoGenerated: true);
            var manualA = Track("es", "Spanish", autoGenerated: false);
            var manualB = Track("fr", "French", autoGenerated: false);

            Assert.Same(first, CaptionTrackSelector.SelectPrimary(new[] { first, manualA, manualB }));
        }
    }
}
